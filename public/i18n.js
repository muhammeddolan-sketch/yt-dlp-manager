let defaultLang = 'en'; // Fallback language
if (typeof navigator !== 'undefined' && navigator.language) {
    const browserLang = navigator.language.split('-')[0];
    if (translations[browserLang]) {
        defaultLang = browserLang;
    }
}
let currentLang = localStorage.getItem('uniget_lang') || defaultLang;
if (!translations[currentLang]) currentLang = defaultLang;
function t(key) {
    const active = translations[currentLang] || translations.en;
    return active[key] || translations.en[key] || key;
}

function setLanguage(lang) {
    if (translations[lang]) {
        currentLang = lang;
        localStorage.setItem('uniget_lang', lang);
        updateUI();
    }
}

function updateUI() {
    // This will be called to update static elements
    // We'll call it after DOM loads and when language changes
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (el.tagName === 'INPUT' && el.type === 'text') {
            el.placeholder = t(key);
        } else {
            el.innerText = t(key);
        }
    });

    // Tooltip-only labels (icon rail buttons etc.)
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        el.title = t(el.getAttribute('data-i18n-title'));
    });

    // Reload list if it's there
    if (typeof renderList === 'function') renderList();
    
    // Notify app if callback exists
    if (window.onLangChange) window.onLangChange(currentLang);

    // Sidebar view label + collapse button tooltips
    if (typeof window.refreshSidebarMeta === 'function') window.refreshSidebarMeta();
}
